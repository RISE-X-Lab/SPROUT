#!/usr/bin/env python3
"""The logo in README.md.

    python3 ops/figures/gen_logo.py   # -> docs/figures/logo.svg, logo-dark.svg, logo-mark.svg
    rsvg-convert -f pdf -o docs/figures/logo-mark.pdf docs/figures/logo-mark.svg   # the mark as PDF

A cartoon seedling: a fat curved stem out of a mound of soil, two big leaves
and a side shoot (the branch). The wordmark and tagline are Nunito, converted
to outlines so the file renders identically everywhere instead of falling
back to whatever sans-serif the viewer has installed (``typeset.py``).
``logo-mark.svg`` is the seedling alone, no text, cropped to its outline.
"""

from __future__ import annotations

import sys
from pathlib import Path

from typeset import nunito, outline

FIGURES = Path(__file__).resolve().parents[2] / "docs" / "figures"

WORDMARK = "sprout"
TAGLINE = "branch an agent rollout from any step"

# Plant outline, leaf, leaf highlight, stem, soil, soil outline, wordmark, tagline
THEMES = {
    "logo": ("#1f4a33", "#6cd07a", "#c4f2a6", "#4bb85e", "#a8683a", "#5a3a1f", "#1f4a33", "#6b7a72"),
    "logo-dark": ("#173727", "#74d982", "#cdf5b0", "#55c268", "#b47340", "#4a2f19", "#eef7f1", "#9fb3a8"),
}


#: the mark alone, cropped to its outline (x 23.7..138.3, y 28.5..144.3 in the logo's
#: coordinates, measured on a render) with a margin of about 4 units
MARK_VIEWBOX = "19.5 24.5 123 124"


def mark(out: str, leaf: str, hi: str, stem: str, soil: str, soil_out: str) -> str:
    return f"""  <g stroke="{soil_out}" stroke-width="4.5" stroke-linejoin="round" stroke-linecap="round">
    <path d="M26 142C30 116 116 116 120 142Z" fill="{soil}"/>
    <g fill="{soil_out}" stroke="none">
      <circle cx="50" cy="134" r="2.2"/>
      <circle cx="94" cy="132" r="2.2"/>
      <circle cx="66" cy="137" r="1.8"/>
    </g>
  </g>
  <g stroke="{out}" stroke-width="4.5" stroke-linejoin="round" stroke-linecap="round">
    <!-- side shoot: the branch -->
    <path d="M84 110C96 110 106 106 112 98" fill="none" stroke-width="13"/>
    <path d="M84 110C96 110 106 106 112 98" fill="none" stroke="{stem}" stroke-width="5.5"/>
    <path d="M112 98C114 86 128 82 136 90C132 102 120 108 112 98Z" fill="{leaf}"/>
    <!-- stem, fatter at the soil -->
    <path d="M63 132C52 116 80 94 74 74L86 74C92 98 76 118 85 132Z" fill="{stem}"/>
    <!-- leaves -->
    <path d="M80 76C60 84 24 64 30 36C44 18 74 50 80 76Z" fill="{leaf}"/>
    <path d="M80 76C100 84 136 64 130 36C116 18 86 50 80 76Z" fill="{leaf}"/>
    <path d="M80 76Q66 62 54 52M80 76Q94 62 106 52" fill="none" stroke-width="3"/>
    <path d="M38 48Q40 38 48 32M122 48Q120 38 112 32" fill="none" stroke="{hi}" stroke-width="4"/>
  </g>
"""


def render(name: str) -> str:
    out, leaf, hi, stem, soil, soil_out, word_c, tag_c = THEMES[name]
    x0 = 170.0
    word, word_w = outline(WORDMARK, nunito(800), 80, x0, 104, tracking_em=-0.01)
    tag, tag_w = outline(TAGLINE, nunito(600), 17.5, x0 + 3, 132)
    width = int(round(x0 + max(word_w, tag_w) + 20))
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="160" '
        f'viewBox="0 0 {width} 160" role="img" aria-label="{WORDMARK}: {TAGLINE}">\n'
        f"  <!-- generated by ops/figures/gen_logo.py; edit that, not this -->\n"
        + mark(out, leaf, hi, stem, soil, soil_out)
        + f'  <path fill="{word_c}" d="{word}"/>\n'
        + f'  <path fill="{tag_c}" d="{tag}"/>\n'
        + "</svg>\n"
    )


def render_mark(name: str) -> str:
    """The seedling without the wordmark and tagline, in the theme's colours."""
    out, leaf, hi, stem, soil, soil_out, _word_c, _tag_c = THEMES[name]
    _, _, width, height = MARK_VIEWBOX.split()
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="{MARK_VIEWBOX}" '
        f'role="img" aria-label="{WORDMARK}">\n'
        f"  <!-- generated by ops/figures/gen_logo.py; edit that, not this -->\n"
        + mark(out, leaf, hi, stem, soil, soil_out)
        + "</svg>\n"
    )


def main() -> int:
    FIGURES.mkdir(exist_ok=True)
    for name in THEMES:
        path = FIGURES / f"{name}.svg"
        path.write_text(render(name))
        print(f"wrote {path}")
    path = FIGURES / "logo-mark.svg"
    path.write_text(render_mark("logo"))
    print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
